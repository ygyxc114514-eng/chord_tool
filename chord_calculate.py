def temp_grade(value):
    """温度值 → 11 档等级名。每档 2 度：0~±2 微，±2~±4 小，±4~±6 中，±6~±8 大，±8~±10 巨。"""
    if value is None:
        return None
    if value == 0:
        return "平衡（中性）"
    k = min(math.ceil(abs(value) / TEMP_GRADE_STEP - 1e-12), 5)
    return TEMP_GRADES[5 + k] if value > 0 else TEMP_GRADES[5 - k]


def resolve_grade(text):
    """输入文本 → 等级名；不是等级名时返回 None。"""
    return GRADE_ALIASES.get(text.strip().replace(" ", ""))


def grade_display(value, label):
    """结果里的档位显示：零档显示“平衡/中性”原标签，其余显示档名。"""
    g = temp_grade(value)
    return label if g == "平衡（中性）" else g



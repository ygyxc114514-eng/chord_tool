_GRADE_INDEX = {g: i for i, g in enumerate(TEMP_GRADES)}


def _tension_band_index(t):
    """动态张力 → 2 度带号 0~9（0-2、2-4、…、18-20）。
    边界沿用温度档惯例：正好落在带界上的值记低带（2.0 归 0-2）。"""
    k = math.ceil(t / 2 - 1e-12) - 1
    return min(max(k, 0), 9)


def _band_label(k2):
    return f"{2 * k2}-{2 * k2 + 2}"


_DIFF_STATIC = None


def _diff_t_band(v):
    """静态温度差 → 2 度档号 0~19（-20~-18、-18~-16、…、18~20）。
    边界口径同温度档：正好落在档界上的值记低档（-18.0 归 -20~-18，0 归 -2~0）。"""
    return min(max(math.ceil((v + 20) * 0.5 - 1e-12) - 1, 0), 19)


def _diff_x_band(v):
    """静态张力差 → 2 度档号 0~9（-10~-8、…、8~10），边界口径同上。"""
    return min(max(math.ceil((v + 10) * 0.5 - 1e-12) - 1, 0), 9)


def _diff_band_label(k, hi):
    """差值档号（0 基）→ 区间文字；hi = 温度差 20 / 张力差 10。"""
    lo = 2 * k - hi
    return f"{lo}~{lo + 2}"


def _decode_cell(s):
    """预存示例串 "a,b;c,d" → [(a, b), …]。"""
    return [tuple(int(v) for v in p.split(",")) for p in s.split(";")]


def _level_sort_key(lv):
    return (int(lv[:-1]), lv[-1])


def _temp_grades_in_range(a, b):
    """温度区间 (a, b] 覆盖到的档：冷侧、平衡、暖侧依次列。"""
    colds = [TEMP_GRADES[5 - k] for k in range(1, 6) if -2 * k < b and -2 * k + 2 > a]
    warms = [TEMP_GRADES[5 + k] for k in range(1, 6) if 2 * (k - 1) < b and 2 * k > a]
    return colds + (["平衡（中性）"] if a < 0 <= b else []) + warms


_RANGE_RE = re.compile(r"(-?\d+(?:\.\d+)?)\s*(?:~|～|到|—|-)\s*(-?\d+(?:\.\d+)?)")


def parse_temperature_cond(text):
    """温度条件 → (档名集合, 说明) 或 None。
    支持：档名（巨暖）；单个数（7 → 大暖、-7 → 大冷、0 → 平衡（中性））；
    区间（6-8、-8~-6、6到8），按 (a, b] 含值口径取档。"""
    grade = resolve_grade(text)
    if grade:
        return {grade}, grade
    m = _RANGE_RE.fullmatch(text.strip())
    if m:
        a, b = float(m.group(1)), float(m.group(2))
        names = _temp_grades_in_range(a, b)
        if names:
            return set(names), f"{a:g}~{b:g} → {'、'.join(names)}"
        return None
    try:
        v = float(text)
    except ValueError:
        return None
    if not math.isfinite(v):
        return None
    return {temp_grade(v)}, f"{v:g} → {temp_grade(v)}"


def parse_static_tension_cond(text):
    """静态张力条件 → (等级集合, 说明) 或 None。
    支持：全等级名（5a、10d）；大等级组号（7 → 组7 的 7a、7b）；
    带小数的张力值按"最接近的等级"（0.645 → 1b）；
    区间：整数按组（4-6 → 组4~组6），带小数按张力值（0.5-2 → 该段张力值的等级）。"""
    t = text.strip()
    m = re.fullmatch(r"(\d{1,2})\s*([a-dA-D])", t)
    if m:
        lv = f"{int(m.group(1))}{m.group(2).lower()}"
        return ({lv}, lv) if lv in LEVEL_ORDER else None
    m = _RANGE_RE.fullmatch(t)
    if m:
        a, b = float(m.group(1)), float(m.group(2))
        if re.fullmatch(r"\d+", m.group(1)) and re.fullmatch(r"\d+", m.group(2)):
            ka, kb = max(int(a), 1), int(b)
            lvs = [lv for lv in LEVEL_ORDER if ka <= int(lv[:-1]) <= kb]
            if not lvs:
                return None
            return set(lvs), f"组 {ka}~组 {kb}（{'、'.join(sorted(lvs, key=_level_sort_key))}）"
        lvs = [lv for lv in LEVEL_ORDER if a < static_tension(lv) <= b]
        if not lvs:
            return None
        return set(lvs), f"张力 {a:g}~{b:g}（{'、'.join(sorted(lvs, key=_level_sort_key))}）"
    try:
        v = float(t)
    except ValueError:
        return None
    if not math.isfinite(v):
        return None
    if "." not in t and 1 <= v <= 10 and v == int(v):
        ka = int(v)
        lvs = [lv for lv in LEVEL_ORDER if int(lv[:-1]) == ka]
        return set(lvs), f"组 {ka}（{'、'.join(sorted(lvs, key=_level_sort_key))}）"
    best = min(LEVEL_ORDER, key=lambda lv: abs(static_tension(lv) - v))
    return {best}, f"{v:g} → {best}（张力 {static_tension(best):.3f}）"


def parse_dynamic_tension_cond(text):
    """动态张力条件 → (张力带号集合, 说明) 或 None。
    单个数按它所在的 2 度带（7.5 → 6-8）；区间 a-b 从 a 所在带的上一带排到
    b 所在带（6-12 → 6-8、8-10、10-12），与计数表同一套含值口径。"""
    t = text.strip()
    m = re.fullmatch(r"(\d+(?:\.\d+)?)\s*(?:~|～|到|—|-)\s*(\d+(?:\.\d+)?)", t)
    if m:
        a, b = float(m.group(1)), float(m.group(2))
        if not (0 <= a <= b <= 20):
            return None
        lo = min(int(a // 2), 9)
        hi = _tension_band_index(b)
        if lo > hi:
            return None
        return (set(range(lo, hi + 1)),
                f"{a:g}~{b:g}（带 {'、'.join(_band_label(k) for k in range(lo, hi + 1))}）")
    try:
        v = float(t)
    except ValueError:
        return None
    if not math.isfinite(v) or v < 0 or v > 20:
        return None
    k = _tension_band_index(v)
    return {k}, f"{v:g} → 带 {_band_label(k)}"


def parse_diff_band_cond(text, hi):
    """差值档条件 → (0 基档号集合, 说明) 或 None。hi = 最大档号（温度差 20、张力差 10）。
    支持：档号 1~hi（如 10）；区间按档号闭区间（3-5、3~5），与计数表同一套档界口径。"""
    t = text.strip()
    m = re.fullmatch(r"(\d{1,2})\s*(?:~|～|到|—|-)\s*(\d{1,2})", t)
    if m:
        a, b = int(m.group(1)), int(m.group(2))
        if not (1 <= a <= b <= hi):
            return None
        lo = 2 * (a - 1) - hi
        hi_v = 2 * (b - 1) - hi + 2
        return set(range(a - 1, b)), f"档 {a}~{b}（{lo}~{hi_v}）"
    if re.fullmatch(r"\d{1,2}", t):
        k = int(t)
        if not (1 <= k <= hi):
            return None
        return {k - 1}, f"档 {k}（{_diff_band_label(k - 1, hi)}）"
    return None



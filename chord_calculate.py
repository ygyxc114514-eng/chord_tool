def query_attr_search():
    """属性查和弦：先选静态/动态，动态里再选 动态温度/张力 或 差值；
    再输温度（差）和/或张力（差）条件（至少一个）。"""
    kind = input("  查静态还是动态？（1 静态 / 2 动态）：").strip()
    if kind in ("1", "静态", "静"):
        dynamic = False
    elif kind in ("2", "动态", "动"):
        sub = input("  查动态温度/张力档，还是查温度差/张力差？（1 动态温度/张力 / 2 差值）：").strip()
        if sub in ("2", "差值", "差"):
            query_diff_search()
            return
        if sub not in ("1", "动态", "动", "温度", "张力", "档"):
            print("  已取消。")
            return
        dynamic = True
    else:
        print("  已取消。")
        return
    t_text = input("  输入温度条件（回车跳过）：").strip()
    x_text = input("  输入张力条件（回车跳过）：").strip()
    if not t_text and not x_text:
        print("  温度和张力至少输一个。")
        return
    grade_set = level_set = gi_set = k2_set = None
    desc_parts = []
    if t_text:
        cond = parse_temperature_cond(t_text)
        if cond is None:
            print(f"  温度条件“{t_text}”无法识别（可用：大暖、7、6-8、-8~-6）。")
            return
        names, disp = cond
        desc_parts.append(f"温度 {disp}")
        if dynamic:
            gi_set = {_GRADE_INDEX[g] for g in names}
        else:
            grade_set = names
    if x_text:
        if dynamic:
            cond = parse_dynamic_tension_cond(x_text)
            if cond is None:
                print(f"  张力条件“{x_text}”无法识别（动态可用：7.5、6-12，范围 0~20）。")
                return
            k2_set, disp = cond
        else:
            cond = parse_static_tension_cond(x_text)
            if cond is None:
                print(f"  张力条件“{x_text}”无法识别（可用：5a、7、0.645、4-6）。")
                return
            level_set, disp = cond
        desc_parts.append(f"张力 {disp}")
    desc = " × ".join(desc_parts)
    mode = input("  随机一个还是全部输出？（1 随机一个 / 2 全部输出）：").strip()
    if mode not in ("1", "2", "随机", "全部"):
        print("  已取消。")
        return
    print("-" * 60)
    if dynamic:
        search_dynamic_attr(gi_set, k2_set, desc, "one" if mode == "1" else "all")
    else:
        search_static_attr(grade_set, level_set, desc, "one" if mode == "1" else "all")



# ========== 五度圈 ==========
CIRCLE = ["C", "G", "D", "A", "E", "B", "F#", "Db", "Ab", "Eb", "Bb", "F"]
N = len(CIRCLE)

NAME_TO_PITCH = {
    "C": 0, "B#": 0,
    "C#": 1, "Db": 1,
    "D": 2,
    "D#": 3, "Eb": 3,
    "E": 4, "Fb": 4,
    "F": 5, "E#": 5,
    "F#": 6, "Gb": 6,
    "G": 7,
    "G#": 8, "Ab": 8,
    "A": 9,
    "A#": 10, "Bb": 10,
    "B": 11, "Cb": 11,
}

PITCH_TO_NAME = {
    0: "C", 1: "Db", 2: "D", 3: "Eb", 4: "E", 5: "F",
    6: "F#", 7: "G", 8: "Ab", 9: "A", 10: "Bb", 11: "B",
}



# ========== 基础计算 ==========
def fifth_span_detail(pitch_classes):
    """
    在五度圈上枚举起点与方向，取第一次覆盖全部和弦音时步数最短的那次遍历。
    返回 (起点索引, 终点索引, 方向, 纯五度跨度, 遍历覆盖的索引列表)
    方向: +1 升序, -1 降序
    """
    notes = {PITCH_TO_NAME[p] for p in pitch_classes}
    notes = {n for n in notes if n in CIRCLE}
    if not notes:
        return None
    positions = {CIRCLE.index(n) for n in notes}
    best = None
    for start in positions:
        for direction in (1, -1):
            covered = []
            distance = 0
            pos = start
            for _ in range(N):
                covered.append(pos)
                if positions.issubset(set(covered)):
                    if best is None or distance < best[3]:
                        best = (start, pos, direction, distance, covered[:])
                    break
                pos = (pos + direction) % N
                distance += 1
    return best


def interval_stats(pitch_classes):
    """返回 (大二度个数, 半音程个数)。

    两者都按音程级统计：小二度(1)和大七度(11)都算，大二度(2)和小七度(10)都算。
    只数 iv==2 会让同一个结构换个八度摆法就少算一个大二度，等级跟着移调漂。
    """
    pitches = sorted(pitch_classes)
    major2 = 0
    semitone = 0
    for i in range(len(pitches)):
        for j in range(i + 1, len(pitches)):
            iv = (pitches[j] - pitches[i]) % 12
            if iv in (2, 10):
                major2 += 1
            if iv in (1, 11):
                semitone += 1
    return major2, semitone


def has_major_or_minor_triad(pitch_classes):
    pitches = sorted(pitch_classes)
    n = len(pitches)
    for i in range(n):
        for j in range(n):
            for k in range(n):
                if i == j or j == k or i == k:
                    continue
                a, b, c = pitches[i], pitches[j], pitches[k]
                if (b - a) % 12 == 4 and (c - a) % 12 == 7:
                    return True
                if (b - a) % 12 == 3 and (c - a) % 12 == 7:
                    return True
    return False


def consecutive_semitone_stats(pitch_classes):
    """统计半音程游程，按十二音环首尾相接。

    B-C-Db 这类跨八度接缝的连续半音算一组，与 interval_stats 的音程级口径一致。
    返回 (最长游程, 长度≥2的游程个数)。
    """
    pitches = sorted(pitch_classes)
    intervals = [(pitches[i + 1] - pitches[i]) % 12
                 for i in range(len(pitches) - 1)]
    intervals.append((pitches[0] - pitches[-1]) % 12)

    break_at = next((i for i, iv in enumerate(intervals) if iv != 1), None)
    if break_at is None:
        # 整个环都是半音阶
        return len(intervals), 0
    intervals = intervals[break_at + 1:] + intervals[:break_at + 1]

    max_run = 0
    cur = 0
    run_count = 0
    for iv in intervals:
        if iv == 1:
            cur += 1
            max_run = max(max_run, cur)
        else:
            if cur >= 2:
                run_count += 1
            cur = 0
    return max_run, run_count



def _dyn_data():
    """动态查找用的组合表，查一次后缓存。
    组合 = (音集, 低音, 等级, 点, 方向, X, 对径音)，等级映射不出半径的组合跳过；
    分三类：对径音（tie，方向无从定号）、圆心（半径 0，乘积恒 0）、外圈。
    dir_hist 是外圈按 X → {等级: [组合号]} 的归类。"""
    global _DYN_DATA
    if _DYN_DATA is not None:
        return _DYN_DATA
    combos = []
    tie_ids = []
    center_ids = []
    outer_ids = []
    dir_hist = {}
    for size in range(2, 13):
        for s in itertools.combinations(range(12), size):
            S = set(s)
            level = get_tension_level(S)[0]
            for bass in s:
                point = chord_point(S, level, bass)
                if point is None:
                    continue
                direction, tie = chord_direction(S, bass)
                cid = len(combos)
                x = int(direction * _DIR_SCALE) % _DIR_MOD
                combos.append((S, bass, level, point, direction, x, tie))
                if tie:
                    tie_ids.append(cid)
                    continue
                if round(math.hypot(point[0], point[1]), 9) == 0:
                    center_ids.append(cid)
                else:
                    outer_ids.append(cid)
                    dir_hist.setdefault(x, {}).setdefault(level, []).append(cid)
    _DYN_DATA = (combos, tie_ids, center_ids, outer_ids, dir_hist)
    return _DYN_DATA


def _dyn_pair_value(cid_a, cid_b):
    """组合号 → 一对具体和弦的动态温度值，走真函数、与展示同一条浮点路径。"""
    combos = _dyn_data()[0]
    a = combos[cid_a]
    b = combos[cid_b]
    return dynamic_temperature(a[3], b[3], a[4], b[4], a[6], b[6])[0]


def format_dyn_pair(cid_a, cid_b):
    """一行展示一对和弦：动态温度、动态张力，外加静态温度差/静态张力差
    （和弦2 − 和弦1，与和声进行那套显示同一口径）。"""
    combos = _dyn_data()[0]
    a = combos[cid_a]
    b = combos[cid_b]

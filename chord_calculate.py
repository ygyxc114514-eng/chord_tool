# ========== 和声进行 ==========
def query_progression(text):
    """两个和弦用 / 隔开。动态张力 = 两个和弦点之间的最短距离；
    动态温度 = 两个和弦点到圆心的距离相乘再乘方向夹角正弦、除以 10，带冷暖。"""
    parts = [p.strip() for p in text.replace("／", "/").split("/")]
    if len(parts) > 2:
        print(f"  目前最多支持两个和弦（收到 {len(parts)} 个）。")
        return
    if len(parts) < 2 or not all(parts):
        print("  和声进行格式：两个和弦用 / 隔开，例如：C E G / D F A")
        return

    chords = []
    for part in parts:
        pitch_classes, names, errors = parse_input(part)
        if errors:
            print(f"  警告：无法识别的音名 {errors}")
            return
        if len(pitch_classes) < 2:
            print(f"  “{part}”至少需要两个不同的音。")
            return
        level, span, (major2, semitone), (max_run, run_count) = get_tension_level(pitch_classes)
        point = chord_point(pitch_classes, level, NAME_TO_PITCH[names[0]])
        chords.append((names, pitch_classes, level, span, major2, semitone, max_run, run_count, point))

    print("-" * 60)
    for names, pitch_classes, level, span, major2, semitone, max_run, run_count, _ in chords:
        print(format_result(names, pitch_classes, level, span, major2, semitone, max_run, run_count))
        print()

    a, b = chords
    point_a, point_b = a[-1], b[-1]
    if point_a is None or point_b is None:
        print("  动态张力：无法计算（有和弦的等级映射不出半径）")
        print("  动态温度：无法计算（有和弦的等级映射不出半径）")
        print("  温度差：无法计算（有和弦的等级映射不出半径）")
        print("  张力差：无法计算（有和弦的等级映射不出半径）")
        return

    direction_a, tie_a = chord_direction(a[1], NAME_TO_PITCH[a[0][0]])
    direction_b, tie_b = chord_direction(b[1], NAME_TO_PITCH[b[0][0]])
    print(f"  动态张力：{dynamic_tension(point_a, point_b):.3f}")
    temp, label = dynamic_temperature(point_a, point_b, direction_a, direction_b, tie_a, tie_b)
    print(f"  动态温度：{temp:+.3f}  ({label})")
    static_a = get_temperature(a[1], a[2], NAME_TO_PITCH[a[0][0]])[0]
    static_b = get_temperature(b[1], b[2], NAME_TO_PITCH[b[0][0]])[0]
    print(f"  温度差：{static_b - static_a:+.3f}")
    print(f"  张力差：{static_tension(b[2]) - static_tension(a[2]):+.3f}")
    print(f"  和弦点方向：{' '.join(a[0])} {math.degrees(point_a[2]) % 360:.1f}° → "
          f"{' '.join(b[0])} {math.degrees(point_b[2]) % 360:.1f}°（圆半径 10）")



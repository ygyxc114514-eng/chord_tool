MAJOR_SCALE = {0, 2, 4, 5, 7, 9, 11}
NATURAL_MINOR = {0, 2, 3, 5, 7, 8, 10}
HARMONIC_MINOR = {0, 2, 3, 5, 7, 8, 11}
MELODIC_MINOR = {0, 2, 3, 5, 7, 9, 11}
HARMONIC_MAJOR = {0, 2, 4, 5, 7, 8, 11}
SCALES = [MAJOR_SCALE, NATURAL_MINOR, HARMONIC_MINOR, MELODIC_MINOR, HARMONIC_MAJOR]


def is_regular_chord(pitch_classes):
    for root in range(12):
        for scale in SCALES:
            transposed = {(p + root) % 12 for p in scale}
            if pitch_classes.issubset(transposed):
                return True
    return False


# ========== 张力等级判断 ==========
def get_tension_level(pitch_classes):
    detail = fifth_span_detail(pitch_classes)
    if detail is None:
        return None, None, None, None
    span = detail[3]

    major2, semitone = interval_stats(pitch_classes)
    has_triad = has_major_or_minor_triad(pitch_classes)
    is_regular = is_regular_chord(pitch_classes)
    max_run, run_count = consecutive_semitone_stats(pitch_classes)

    # 逐条严格对应规则原文，任何一条都不满足时保持 None（无法归类）
    level = None

    if semitone == 0:
        if 2 <= span <= 4:
            if major2 <= 1:
                level = "1a" if has_triad else "1b"
            elif major2 in (2, 3):
                level = "1c"
        elif span == 6:
            if major2 <= 1:
                level = "2a" if has_triad else "2b"
            elif major2 in (2, 3):
                level = "2c"
        elif 7 <= span <= 11:
            if span == 8 and major2 <= 1:
                level = "3a"
            elif span == 8 and major2 == 2:
                level = "3b"
            elif major2 > 2 or span > 8:
                level = "3c"

    elif semitone == 1:
        if span == 5:
            if major2 > 2 or not has_triad:
                level = "4c"
            elif major2 == 2:
                level = "4b"
            else:
                level = "4a"
        elif span == 6:
            if major2 > 2 or not has_triad:
                level = "5c"
            elif major2 == 2:
                level = "5b"
            elif major2 <= 1:
                level = "5a"
        elif 7 <= span <= 11:
            if major2 > 2 or not has_triad:
                level = "6c"
            elif major2 == 0:
                level = "6a"
            elif major2 in (1, 2):
                level = "6b"

    elif semitone == 2:
        if span == 6:
            if major2 > 1 or not has_triad:
                level = "7b"
            elif major2 <= 1:
                level = "7a"
        elif 7 <= span <= 11:
            if is_regular:
                if major2 <= 2 and has_triad:
                    level = "8a"
                elif major2 > 2 or not has_triad:
                    level = "8b"
            else:
                if major2 <= 3 and has_triad:
                    level = "8c"
                elif major2 > 3 or not has_triad:
                    level = "8d"

    elif semitone == 3:
        if 7 <= span <= 11:
            if max_run >= 3:
                level = "9c"
            elif max_run == 2:
                level = "9b"
            elif max_run <= 1:
                level = "9a"

    elif semitone >= 4:
        if 7 <= span <= 11:
            if max_run >= 4:
                level = "10d"
            elif max_run == 3:
                level = "10c"
            elif max_run == 2 and run_count >= 2:
                level = "10b"
            else:
                # 原著 X 行漏格：只有一组连续两个（或半音全孤立）。用户决定补的这格现名 10a。
                level = "10a"

    return level, span, (major2, semitone), (max_run, run_count)
